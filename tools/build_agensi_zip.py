#!/usr/bin/env python3
"""Build the self-contained Agensi edition ZIP archive."""

from __future__ import annotations

import os
from pathlib import Path
import re
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "src" / "ctxdock"
AGRESI_DIR = ROOT / "marketplace" / "agensi"
SCRIPTS_DIR = AGRESI_DIR / "scripts"
DIST_DIR = ROOT / "dist"

MODULE_ORDER = [
    "security.py",
    "records.py",
    "projects.py",
    "index.py",
    "storage.py",
    "installer.py",
    "cli.py",
]


def clean_module_code(filename: str, code: str) -> str:
    lines: list[str] = []
    in_module_docstring = False
    past_header = False

    for line in code.splitlines():
        stripped = line.strip()

        # Handle module-level docstrings only at the top of the file
        if not past_header:
            if not in_module_docstring and (stripped.startswith('"""') or stripped.startswith("'''")):
                if (stripped.endswith('"""') or stripped.endswith("'''")) and len(stripped) > 6:
                    past_header = True
                    continue
                in_module_docstring = True
                continue
            if in_module_docstring:
                if stripped.endswith('"""') or stripped.endswith("'''"):
                    in_module_docstring = False
                    past_header = True
                continue

        # Skip from __future__
        if stripped.startswith("from __future__"):
            continue

        # Skip relative package imports
        if stripped.startswith("from .") or stripped.startswith("from ctxdock"):
            continue

        if stripped and not stripped.startswith("#"):
            past_header = True

        lines.append(line)

    return "\n".join(lines)


def generate_standalone_script() -> Path:
    SCRIPTS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = SCRIPTS_DIR / "ctxdock.py"

    header = '''#!/usr/bin/env python3
"""CtxDock standalone runner for Agensi and portable agent environments.

This file is automatically generated from the validated core in src/ctxdock/.
Do not edit manually. Run tools/build_agensi_zip.py to rebuild.
"""

from __future__ import annotations

import argparse
from contextlib import contextmanager, redirect_stderr, redirect_stdout
from datetime import datetime, timezone
from difflib import SequenceMatcher
import filecmp
import hashlib
from importlib import resources
import io
import json
import os
from pathlib import Path
import re
import shutil
import sqlite3
import statistics
import subprocess
import sys
import tempfile
import time
from typing import Any, Iterable, Iterator, Sequence
import uuid

__version__ = "0.1.0"

'''
    chunks = [header]

    for mod_name in MODULE_ORDER:
        mod_path = SRC_DIR / mod_name
        if not mod_path.is_file():
            raise FileNotFoundError(f"Missing core module: {mod_path}")
        raw = mod_path.read_text(encoding="utf-8")
        cleaned = clean_module_code(mod_name, raw)
        chunks.append(f"# --- Begin {mod_name} ---\n{cleaned}\n# --- End {mod_name} ---\n")
        if mod_name == "index.py":
            chunks.append('''
class _IndexProxy:
    initialize = staticmethod(initialize)
    upsert = staticmethod(upsert)
    search = staticmethod(search)
    connect = staticmethod(connect)
    rebuild = staticmethod(rebuild)
    get_schema_version = staticmethod(get_schema_version)
    set_schema_version = staticmethod(set_schema_version)

index = _IndexProxy()
''')
        elif mod_name == "installer.py":
            chunks.append('''
install_skill = install
uninstall_skill = uninstall
''')

    chunks.append('''
if __name__ == "__main__":
    raise SystemExit(main())
''')

    full_script = "\n".join(chunks)
    out_path.write_text(full_script, encoding="utf-8")
    print(f"Generated standalone script at {out_path} ({len(full_script):,} bytes).")
    return out_path


def build_zip() -> Path:
    generate_standalone_script()

    # Ensure required files exist
    required_files = [
        AGRESI_DIR / "SKILL.md",
        AGRESI_DIR / "LICENSE",
        AGRESI_DIR / "scripts" / "ctxdock.py",
        AGRESI_DIR / "references" / "commands.md",
        AGRESI_DIR / "references" / "privacy.md",
    ]

    for path in required_files:
        if not path.is_file():
            raise FileNotFoundError(f"Required Agensi file missing: {path}")

    DIST_DIR.mkdir(parents=True, exist_ok=True)
    zip_path = DIST_DIR / "ctxdock-agensi-0.1.0.zip"
    if zip_path.exists():
        zip_path.unlink()

    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for file_path in required_files:
            rel = file_path.relative_to(AGRESI_DIR).as_posix()
            z.write(file_path, arcname=rel)

    size = zip_path.stat().st_size
    print(f"Created {zip_path} ({size:,} bytes).")
    return zip_path


def main() -> int:
    build_zip()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
